def echo_text(s: str) -> str:
    return s


def echo_number(n: int) -> int:
    return n


def echo_name_and_age(name: str, age: int) -> tuple[str, int]:
    return name, age


def echo_text_and_number(s: str, n: int) -> tuple[str, int]:
    return s, n


def echo_numbers(n: int, x: float, y: float) -> tuple[int, float, float]:
    return n, x, y


def echo_flag(b: bool) -> bool:
    return b
